// Writes brand.css (plain CSS custom properties) from src/tokens.ts, the one place the values are defined.
//   node scripts/build-css.mjs           write brand.css
//   node scripts/build-css.mjs --check   exit 1 if brand.css is not what the tokens give
// Node loads tokens.ts with its built-in type stripping (Node >= 22.18 / 23.6).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as t from '../src/tokens.ts';

const OUT = fileURLToPath(new URL('../brand.css', import.meta.url));

/** `--mantine-color-body` → `--brand-body`, `--mantine-shadow-xs` → `--brand-shadow-xs`, `--surface` → `--brand-surface`. */
const brandName = (name) => '--brand-' + name.replace(/^--(mantine-color-|mantine-)?/, '');
const rem = (px) => `${px / 16}rem`;
const block = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')}\n}\n`;

export function renderBrandCss() {
  const light = {
    '--brand-font-family': t.fontFamily,
    '--brand-font-family-monospace': t.fontFamilyMonospace,
    '--brand-heading-font-weight': t.headingFontWeight,
    '--brand-font-size-body': t.bodyFontSize,
    ...Object.fromEntries(Object.entries({ ...t.extraFontSizes, ...t.baseFontSizes }).map(([k, v]) => [`--brand-font-size-${k}`, rem(v)])),
    ...Object.fromEntries(Object.entries({ ...t.extraSpacing, ...t.baseSpacing }).map(([k, v]) => [`--brand-spacing-${k}`, rem(v)])),
    ...Object.fromEntries(Object.entries(t.radius).map(([k, v]) => [`--brand-radius-${k}`, v])),
    ...Object.fromEntries(t.brandColors.map((c, i) => [`--brand-color-${i}`, c])),
    '--brand-primary': t.brandColors[t.primaryShade],
    '--brand-primary-hover': t.brandColors[t.primaryShade + 1],
    '--brand-accent-strong': t.brandColors[t.accentStrongShade],
    '--brand-accent-strong-hover': t.brandColors[t.accentStrongShade + 1],
    '--brand-on-primary': t.white,
    '--brand-white': t.white,
    '--brand-black': t.black,
    ...Object.fromEntries(Object.entries(t.shadows).map(([k, v]) => [`--brand-shadow-${k}`, v])),
    ...Object.fromEntries(Object.entries(t.schemeVariables.light).map(([k, v]) => [brandName(k), v])),
  };
  const dark = Object.fromEntries(Object.entries(t.schemeVariables.dark).map(([k, v]) => [brandName(k), v]));
  return `/* GENERATED by packages/brand/scripts/build-css.mjs from src/tokens.ts — do not edit (npm run build:css -w packages/brand).
   Asterius design tokens as plain CSS custom properties, for pages without Mantine (hosted sign-in pages).
   One green accent: --brand-primary (#10a37f) is the consoles' primary (filled buttons, selection);
   --brand-accent-strong (#0b7a5e) is the default accent of hosted pages (filled buttons and links, AA under white
   text and on white). Light values on :root; the dark scheme follows Mantine's attribute. Typeface: Inter Variable
   (each app bundles it; the stack falls back to the system UI font). */
${block(':root', light)}
${block("[data-mantine-color-scheme='dark']", dark)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = renderBrandCss();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== css) {
      console.error('brand.css is stale: run `npm run build:css -w packages/brand`.');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, css);
  }
}
